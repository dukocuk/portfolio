// Generates the case-study image variants and the manifest that
// src/lib/caseStudyImages.ts reads.
//
// This replaces Vite's `import.meta.glob` + vite-imagetools, which have no
// Next.js equivalent. The authoring rule it preserves is the important part:
// drop an image into src/assets/case-studies/{project-id}/ and it appears in
// that project's gallery — there is no list to register it in.
//
// Runs ahead of `next dev` and `next build` (see package.json). Outputs are
// gitignored: they are derived from the sources next to them.

import { createHash } from 'node:crypto';
import { mkdir, copyFile, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_DIR = join(root, 'src/assets/case-studies');
const OUTPUT_DIR = join(root, 'public/case-studies');
const MANIFEST = join(root, 'src/lib/caseStudyImages.generated.ts');

// Mirrors the old vite-imagetools query strings exactly, so the migration is
// not also a silent change in image quality.
const VARIANTS = [
  { suffix: '1600', width: 1600, quality: 80 },
  { suffix: '480', width: 480, quality: 75 },
];

const ENCODE_EXT = new Set(['.png', '.jpg', '.jpeg']);
const PASSTHROUGH_EXT = new Set(['.webp', '.gif', '.svg']);

async function listProjects() {
  try {
    const entries = await readdir(SOURCE_DIR, { withFileTypes: true });
    return entries.filter((e) => e.isDirectory()).map((e) => e.name);
  } catch (err) {
    if (err.code === 'ENOENT') return [];
    throw err;
  }
}

// Numeric collation so image10 sorts after image2, not after image1 — the
// galleries are read in order and this is load-bearing.
const byFilename = (a, b) => a.localeCompare(b, undefined, { numeric: true });

async function main() {
  const projects = await listProjects();
  const manifest = {};
  let encoded = 0;
  let reused = 0;

  // The output tree is fully derived. Rebuilding it from scratch each run is
  // what keeps a deleted or renamed source from leaving a stale file behind
  // that nginx would then serve forever under its immutable cache rule.
  await rm(OUTPUT_DIR, { recursive: true, force: true });

  // Content hashes let nginx cache these immutably; reuse them as the cache key
  // for the encode itself, so an unchanged image is not re-encoded every run.
  const cacheDir = join(root, 'node_modules/.cache/case-images');
  await mkdir(cacheDir, { recursive: true });

  for (const id of projects.sort(byFilename)) {
    const files = (await readdir(join(SOURCE_DIR, id))).sort(byFilename);
    const bucket = [];

    for (const filename of files) {
      const ext = extname(filename).toLowerCase();
      const source = join(SOURCE_DIR, id, filename);
      const base = filename.slice(0, -ext.length);
      const outDir = join(OUTPUT_DIR, id);
      await mkdir(outDir, { recursive: true });

      if (PASSTHROUGH_EXT.has(ext)) {
        // Already web-ready (or unrasterizable, for svg) — copied through, as
        // the vite-imagetools setup did.
        const buffer = await readFile(source);
        const hash = createHash('sha256').update(buffer).digest('hex').slice(0, 8);
        const name = `${base}.${hash}${ext}`;
        await copyFile(source, join(outDir, name));
        const url = `/case-studies/${id}/${name}`;
        bucket.push({ filename, src: url, thumb: url });
        continue;
      }

      if (!ENCODE_EXT.has(ext)) continue;

      const buffer = await readFile(source);
      const hash = createHash('sha256').update(buffer).digest('hex').slice(0, 8);
      const urls = {};

      for (const { suffix, width, quality } of VARIANTS) {
        const name = `${base}.${hash}-${suffix}.webp`;
        const cached = join(cacheDir, `${id}-${name}`);
        try {
          await copyFile(cached, join(outDir, name));
          reused += 1;
        } catch {
          // `withoutEnlargement` matches imagetools: an image narrower than the
          // target width is left at its own size rather than upscaled.
          await sharp(buffer)
            .resize({ width, withoutEnlargement: true })
            .webp({ quality })
            .toFile(cached);
          await copyFile(cached, join(outDir, name));
          encoded += 1;
        }
        urls[suffix] = `/case-studies/${id}/${name}`;
      }

      bucket.push({ filename, src: urls['1600'], thumb: urls['480'] });
    }

    if (bucket.length > 0) manifest[id] = bucket.map(({ src, thumb }) => ({ src, thumb }));
  }

  const body = `// GENERATED by scripts/build-case-images.mjs — do not edit.
// Add images by dropping them into src/assets/case-studies/{project-id}/.

export type GeneratedImage = { src: string; thumb: string };

export const caseStudyImageManifest: Record<string, GeneratedImage[]> = ${JSON.stringify(
    manifest,
    null,
    2,
  )};
`;

  await mkdir(dirname(MANIFEST), { recursive: true });
  await writeFile(MANIFEST, body, 'utf8');

  const total = Object.values(manifest).reduce((n, b) => n + b.length, 0);
  console.log(
    `[case-images] ${total} images across ${Object.keys(manifest).length} projects ` +
      `(${encoded} encoded, ${reused} cached) -> ${relative(root, OUTPUT_DIR)}`,
  );
}

main().catch((err) => {
  console.error('[case-images] failed:', err);
  process.exit(1);
});
